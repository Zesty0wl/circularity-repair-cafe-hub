// =============================================================================
//  The Worker
//  ---------------------------------------------------------------------------
//  One Worker serves the whole hub. Cloudflare answers requests for static
//  files (scripts, styles, fonts, images in the web build) before this code
//  runs. Everything else arrives here:
//
//    /api/*, /uploads/*, /og/*, /icons/*, the manifest, robots.txt and
//    sitemap.xml go to the API (src/app.ts)
//
//    every other path is a page, drawn by SvelteKit. When a page needs data
//    while it is being drawn, its calls to /api come straight back into the
//    API through HUB_API, without leaving the Worker
//
//  The jobs the old Docker edition ran on a timer run at most once an hour, after
//  a request has been answered (see housekeeping.ts), and also from scheduled()
//  if the account has a cron trigger to spare.
// =============================================================================
// The SvelteKit Worker is generated by the web build (HUB_TARGET=cloudflare).
// @ts-ignore: generated JavaScript with no type information.
import sveltekit from '../../web/.svelte-kit/cloudflare/_worker.js';
import { handleApi, isApiPath } from './app.js';
import { runScheduled } from './scheduled.js';
import { maybeRunHousekeeping } from './housekeeping.js';

interface Env {
  [key: string]: unknown;
}

const svelte = sveltekit as ExportedHandler<Env>;

/**
 * The headers @fastify/helmet sets in the old Docker edition, minus the content
 * security policy, which SvelteKit sets for each page (svelte.config.js).
 */
const SECURITY_HEADERS: Record<string, string> = {
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Origin-Agent-Cluster': '?1',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Strict-Transport-Security': 'max-age=63072000; includeSubDomains',
  'X-Content-Type-Options': 'nosniff',
  'X-DNS-Prefetch-Control': 'off',
  'X-Download-Options': 'noopen',
  'X-Frame-Options': 'SAMEORIGIN',
  'X-Permitted-Cross-Domain-Policies': 'none',
  'X-XSS-Protection': '0',
};

// ── A short-lived copy of public pages ───────────────────────────────────────
//
// Drawing a public page on the server is the most CPU this Worker spends on
// an ordinary request (tens of milliseconds for the home page), and the free
// plan allows about 10 ms. Visitors who are not signed in all see the same
// page, so a copy is kept in Cloudflare's cache for a minute and handed out
// again. Staff, who carry the sign-in cookie, always get a fresh page, so an
// admin sees their own edits straight away. Everything private (the admin and
// repairer areas, check-in, tracking, setup) is never cached.
//
// The cache only exists on a real domain, not on workers.dev, where this
// quietly does nothing.
const PAGE_CACHE_SECONDS = 60;
const CACHEABLE_PAGE = /^\/(?:$|events(?:\/[^/]+)?$|skills$|team\/[^/]+$|guides(?:\/[^/]+)?$|about$|contact$|world$|linux$)/;

function isCacheablePage(request: Request, url: URL): boolean {
  if (request.method !== 'GET') return false;
  if (!CACHEABLE_PAGE.test(url.pathname)) return false;
  if (request.headers.has('authorization')) return false;
  if (/(?:^|;\s*)circ_refresh=/.test(request.headers.get('cookie') ?? '')) return false;
  return true;
}

function pageCacheKey(url: URL): Request {
  // The query string matters (guide searches, for example), the fragment never
  // reaches us, and nothing else about the request changes the page.
  return new Request(`${url.origin}${url.pathname}${url.search}`, { method: 'GET' });
}

async function cachedPage(url: URL): Promise<Response | null> {
  try {
    const hit = await caches.default.match(pageCacheKey(url));
    if (!hit) return null;
    const res = new Response(hit.body, hit);
    // The browser should still check back each time, as for a fresh page.
    res.headers.set('Cache-Control', 'no-cache');
    res.headers.set('X-Hub-Cache', 'hit');
    return res;
  } catch {
    return null;
  }
}

function keepPage(url: URL, response: Response, ctx: ExecutionContext): void {
  if (response.status !== 200) return;
  if (!(response.headers.get('content-type') ?? '').includes('text/html')) return;
  if (response.headers.has('set-cookie')) return;
  try {
    const copy = new Response(response.clone().body, response);
    copy.headers.set('Cache-Control', `public, max-age=${PAGE_CACHE_SECONDS}`);
    ctx.waitUntil(caches.default.put(pageCacheKey(url), copy).catch(() => {}));
  } catch {
    // Not worth failing a page over.
  }
}

function withSecurityHeaders(response: Response): Response {
  // Some responses (a redirect, a cached asset) have headers that cannot be
  // changed, so work on a copy.
  const out = new Response(response.body, response);
  for (const [name, value] of Object.entries(SECURITY_HEADERS)) {
    if (!out.headers.has(name)) out.headers.set(name, value);
  }
  return out;
}

export default {
  async fetch(request, env, ctx): Promise<Response> {
    const url = new URL(request.url);
    // In the background, once the answer has gone: the hourly jobs, if due.
    ctx.waitUntil(maybeRunHousekeeping());
    if (isApiPath(url.pathname)) {
      return withSecurityHeaders(await handleApi(request));
    }
    const cacheable = isCacheablePage(request, url);
    if (cacheable) {
      const hit = await cachedPage(url);
      if (hit) return withSecurityHeaders(hit);
    }
    const response = await svelte.fetch!(
      request as Request<unknown, IncomingRequestCfProperties>,
      { ...env, HUB_API: (inner: Request) => handleApi(inner) },
      ctx,
    );
    if (cacheable) keepPage(url, response, ctx);
    return withSecurityHeaders(response);
  },

  async scheduled(controller, _env, ctx): Promise<void> {
    ctx.waitUntil(runScheduled(controller.scheduledTime));
  },
} satisfies ExportedHandler<Env>;
