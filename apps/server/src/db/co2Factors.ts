// =============================================================================
//  Reference data for the CO2 figure
//  ---------------------------------------------------------------------------
//  Average weight and pre-use CO2e (the carbon emitted making and shipping a
//  product) for the kinds of thing people bring to a repair cafe.
//
//  Source: "Fixometer reference data" (2021) by The Restart Project,
//  https://zenodo.org/records/5900046  (DOI 10.5281/zenodo.5900046)
//  Licensed CC BY-SA 4.0. Categories follow the Open Repair Data Standard, so a
//  cafe's own records could be shared with the Open Repair Alliance one day.
//
//  `sample` is how many real products the average came from. Some rest on a
//  single product, so we keep the number and show it rather than hide it.
//  Two categories have no CO2e figure at all; they are kept so the item type
//  can still be recorded, and they simply produce no saving.
//
//  `category` is our own grouping, not the standard's. The standard is built
//  around electricals and puts bicycles, clothing, furniture and jewellery
//  together in one "Non-EEE" bucket, which is no use to a repair cafe. The
//  grouping only decides which types are offered first at check-in; a search
//  box covers everything else.
//
//  Regenerating: see docs/proposal-co2-savings.md.
// =============================================================================

